/**
 * Generates src/styles/themes.css (the named color palettes) from the palette
 * data in src/shared/theme-palettes.ts. The file is committed so tooling that
 * never runs the build (tests, editors) sees it; tests/unit/themes.test.ts fails
 * when it is stale, and every build rewrites it first.
 *
 *   node scripts/build-themes.mjs [--check]
 */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { allPalettesCss } from '../src/shared/theme-tokens.ts'

const root = path.resolve(fileURLToPath(import.meta.url), '../..')
const target = path.join(root, 'src/styles/themes.css')

export function themesCss() {
  return `/* GENERATED by scripts/build-themes.mjs from src/shared/theme-palettes.ts. Do not edit.
   One rule per named palette; only custom properties and color-scheme. Screen only:
   printed pages always use the light Cadmium base in tokens.css. */
${allPalettesCss()}`
}

export async function writeThemesCss() {
  const css = themesCss()
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current !== css) await writeFile(target, css)
  return css
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const current = await readFile(target, 'utf8').catch(() => '')
    if (current !== themesCss()) {
      console.error('src/styles/themes.css is stale: run `node scripts/build-themes.mjs`')
      process.exit(1)
    }
  } else {
    await writeThemesCss()
    console.log('wrote src/styles/themes.css')
  }
}
