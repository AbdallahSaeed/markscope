/**
 * Color inputs for the named themes. Each palette is a handful of colors taken from
 * the project's published palette; `theme-tokens.ts` derives every CSS token from
 * them (and nudges lightness where a faithful color would be unreadable as text).
 *
 * Required: `bg` and `fg`, `accent`, `danger`, the five callout colors and the seven
 * syntax colors. Optional surfaces (`bg2`, `bg3`, `raised`) and text shades (`fg2`,
 * `fg3`) are derived from `bg`/`fg` when a theme has no fitting color of its own.
 * `tests/unit/themes.test.ts` fails if an id here is missing from the registry.
 */

